#numeric

xx= 5.6
print(class(xx))
print(typeof(xx))

#integer
yy = as.integer(56)
print(class(yy))
print(typeof(yy))

yl = 5L
print(class(yl))
print(typeof(yl))

#logical
x = 4
y = 3

z = x>y
print(z)
print(class(z))
print(typeof(z))

#complex
xxx = 4+3i
print(class(xxx))
print(typeof(xxx))

#character
char = "accomplishments and flaws can coexist"
print(class(char))
print(typeof(char))

#raw data
aa <- as.raw(c(0x1, 0x2, 0x3, 0x4, 0x5))
print(a)